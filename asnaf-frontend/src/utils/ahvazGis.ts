/**
 * محاسبه مختصات جغرافیایی دقیق برای پرونده‌های بازرسی واحدهای صنفی
 */
export function getUnitLatLng(unit: {
  id: number;
  name: string;
  region?: string | undefined;
  address?: string | undefined;
}): [number, number] {
  let baseCoords: [number, number] | undefined;

  const searchTxt = `${unit.region || ''} ${unit.address || ''} ${unit.name || ''}`;
  for (const n of ahvazNeighborhoods) {
    if (searchTxt.includes(n.name)) {
      baseCoords = n.center;
      break;
    }
  }

  if (!baseCoords) {
    for (const [place, coords] of Object.entries(placeCenterMap)) {
      if (searchTxt.includes(place)) {
        baseCoords = coords;
        break;
      }
    }
  }

  const base = baseCoords ?? AHVAZ_CENTER;
  const seed = unit.id || 1000;
  const latOffset = (((seed * 19) % 100) - 50) * 0.00012;
  const lngOffset = (((seed * 37) % 100) - 50) * 0.00014;

  return [
    Number((base[0] + latOffset).toFixed(6)),
    Number((base[1] + lngOffset).toFixed(6)),
  ];
}

/**
 * هدایت به مسیریابی از مکان فعلی کاربر به سمت مقصد تعیین شده (با Google Maps و اپلیکیشن‌های ناوبری موبایل نظیر نشان و بلد)
 */
export function navigateToLocation(
  destLat: number,
  destLng: number,
  onNotify?: (msg: string) => void
): void {
  if (onNotify) {
    onNotify('در حال دریافت موقعیت مکانی زنده و اتصال به مسیریاب...');
  }

  if (typeof navigator !== 'undefined' && 'geolocation' in navigator) {
    navigator.geolocation.getCurrentPosition(
      (pos) => {
        const userLat = pos.coords.latitude;
        const userLng = pos.coords.longitude;
        const url = `https://www.google.com/maps/dir/?api=1&origin=${userLat},${userLng}&destination=${destLat},${destLng}&travelmode=driving`;
        window.open(url, '_blank');
      },
      () => {
        const url = `https://www.google.com/maps/dir/?api=1&destination=${destLat},${destLng}&travelmode=driving`;
        window.open(url, '_blank');
      },
      { timeout: 5000, enableHighAccuracy: true }
    );
  } else {
    const url = `https://www.google.com/maps/dir/?api=1&destination=${destLat},${destLng}&travelmode=driving`;
    window.open(url, '_blank');
  }
}
