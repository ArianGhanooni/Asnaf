/**
 * محاسبه رنگ حرارتی محله بر اساس تعداد مأموریت‌ها نسبت به سقف مأموریت‌ها
 */
export function getNeighborhoodHeatStyle(count: number, maxCount: number): HeatStyle {
  if (count <= 0) {
    return HEAT_PALETTE.idle; // سبز: مأموریت در محله نیست
  }
  if (maxCount <= 0) {
    return HEAT_PALETTE.idle;
  }
  const ratio = count / maxCount;
  if (ratio >= 0.75 || count === maxCount) {
    return HEAT_PALETTE.critical; // قرمز: بیشترین مأموریت
  }
  if (ratio >= 0.40) {
    return HEAT_PALETTE.busy; // نارنجی: نسبتاً شلوغ
  }
  return HEAT_PALETTE.normal; // آبی: وضعیت عادی
}

