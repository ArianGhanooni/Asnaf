export function findNeighborhoodByCoords(lat: number, lng: number): AhvazNeighborhood | undefined {
  const pt: [number, number] = [lat, lng];
  const insideMatch = ahvazNeighborhoods.find((n) => isPointInPolygon(pt, n.polygon));
  if (insideMatch) {
    return insideMatch;
  }
  let nearest: AhvazNeighborhood | undefined;
  let minDistance = Infinity;
  for (const n of ahvazNeighborhoods) {
    const dLat = n.center[0] - lat;
    const dLng = n.center[1] - lng;
    const distSq = dLat * dLat + dLng * dLng;
    if (distSq < minDistance) {
      minDistance = distSq;
      nearest = n;
    }
  }
  return nearest;
}

